const ASCII_LIMIT = 0x80;

const transliterate = (point: number): string => {
  if (point < ASCII_LIMIT) {
    return String.fromCodePoint(point);
  }

  for (const [start, table] of UNIDECODE_BLOCKS) {
    if (point >= start && point < start + table.length) {
      return table[point - start] ?? "";
    }
  }

  return "";
};

export const asciiFold = (text: string): string =>
  Array.from(text, (char) => transliterate(char.codePointAt(0) ?? 0)).join("");
